public class CalculadoraMediaIdade {

    public static void main (String[] args) {
        int minhaIdade = 23;
        int suaIdade = 45;
        int idadeJoao = 50;

        int idadeMedia = (minhaIdade + suaIdade + idadeJoao) / 3;

        System.out.println("\nIdade média: " + idadeMedia + "\n");
    }
}
