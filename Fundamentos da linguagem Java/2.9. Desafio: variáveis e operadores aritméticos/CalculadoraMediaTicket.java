public class CalculadoraMediaTicket {

    public static void main (String[] args) {
        int primeiraVenda = 20;
        int segundaVenda = 30;
        int terceiraVenda = 100;

        int mediaTicket = (primeiraVenda + segundaVenda + terceiraVenda) / 3;

        System.out.println("\nMedia de tickets: " + mediaTicket + "\n");
    }
}
